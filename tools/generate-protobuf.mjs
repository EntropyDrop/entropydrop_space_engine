import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const protoDir = join(appRoot, 'proto');
const protoFiles = ['inventory.proto', 'backpack.proto', 'space_api.proto'];
const generatedDir = join(appRoot, 'src', 'generated');
const descriptorModuleName = 'inventory_descriptor.ts';
const checkOnly = process.argv.includes('--check');
const temporaryRoot = mkdtempSync(join(tmpdir(), 'space-protobuf-'));
const outputDir = checkOnly ? join(temporaryRoot, 'generated') : generatedDir;
// Generated bindings embed the protoc version, so a different toolchain produces
// different files. Fail loudly instead of checking in machine-specific output.
const EXPECTED_PROTOC_VERSION = '33.2';

function assertProtocVersion() {
  const result = spawnSync('protoc', ['--version'], { encoding: 'utf8' });
  if (result.error) throw result.error;
  const version = `${result.stdout || ''}${result.stderr || ''}`.trim();
  if (!version.includes(EXPECTED_PROTOC_VERSION)) {
    throw new Error(
      `Expected protoc ${EXPECTED_PROTOC_VERSION} but found "${version}". `
      + 'Install the pinned toolchain before generating or checking Protobuf bindings.',
    );
  }
}

function runProtoc(arguments_) {
  const result = spawnSync('protoc', arguments_, {
    cwd: protoDir,
    encoding: 'utf8',
  });
  if (result.stdout) process.stdout.write(result.stdout);
  if (result.stderr) process.stderr.write(result.stderr);
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`protoc failed with exit code ${result.status}`);
}

function renderDescriptorModule(descriptor, sourceHashes) {
  const base64 = descriptor.toString('base64');
  const chunks = base64.match(/.{1,100}/g) || [''];
  const encoded = chunks.map((chunk, index) => (
    `${index === 0 ? '  ' : '  + '}'${chunk}'`
  )).join('\n');
  return `// Code generated by tools/generate-protobuf.mjs. DO NOT EDIT.\n\n`
    + `export const INVENTORY_PROTO_SOURCE_SHA256 = '${sourceHashes.inventory}';\n`
    + `export const BACKPACK_PROTO_SOURCE_SHA256 = '${sourceHashes.backpack}';\n`
    + `export const SPACE_API_PROTO_SOURCE_SHA256 = '${sourceHashes.spaceApi}';\n\n`
    + `const INVENTORY_DESCRIPTOR_SET_BASE64 =\n${encoded};\n\n`
    + `const descriptorBinary = globalThis.atob(INVENTORY_DESCRIPTOR_SET_BASE64);\n`
    + `export const INVENTORY_DESCRIPTOR_SET_BYTES = Uint8Array.from(\n`
    + `  descriptorBinary,\n`
    + `  character => character.charCodeAt(0),\n`
    + `);\n`;
}

function assertGeneratedFileMatches(fileName, expected) {
  const checkedIn = readFileSync(join(generatedDir, fileName), 'utf8');
  if (checkedIn !== expected) {
    throw new Error(`${fileName} is stale; run npm run generate:protobuf`);
  }
}

try {
  assertProtocVersion();
  mkdirSync(outputDir, { recursive: true });
  const plugin = resolve(appRoot, 'node_modules/.bin/protoc-gen-ts_proto');
  runProtoc([
    `--plugin=protoc-gen-ts_proto=${plugin}`,
    `--ts_proto_out=${outputDir}`,
    '--ts_proto_opt=esModuleInterop=true,forceLong=number,useOptionals=all,outputJsonMethods=false,outputClientImpl=false,enumsAsLiterals=true,oneof=unions-value,importSuffix=.ts',
    '-I',
    protoDir,
    ...protoFiles,
  ]);

  const descriptorPath = join(temporaryRoot, 'inventory.binpb');
  runProtoc([
    '-I',
    protoDir,
    '--include_imports',
    `--descriptor_set_out=${descriptorPath}`,
    ...protoFiles,
  ]);
  const sourceHashes = {
    inventory: createHash('sha256')
      .update(readFileSync(join(protoDir, 'inventory.proto')))
      .digest('hex'),
    backpack: createHash('sha256')
      .update(readFileSync(join(protoDir, 'backpack.proto')))
      .digest('hex'),
    spaceApi: createHash('sha256')
      .update(readFileSync(join(protoDir, 'space_api.proto')))
      .digest('hex'),
  };
  const descriptorModule = renderDescriptorModule(readFileSync(descriptorPath), sourceHashes);

  if (checkOnly) {
    assertGeneratedFileMatches('inventory.ts', readFileSync(join(outputDir, 'inventory.ts'), 'utf8'));
    assertGeneratedFileMatches('backpack.ts', readFileSync(join(outputDir, 'backpack.ts'), 'utf8'));
    assertGeneratedFileMatches('space_api.ts', readFileSync(join(outputDir, 'space_api.ts'), 'utf8'));
    assertGeneratedFileMatches(descriptorModuleName, descriptorModule);
  } else {
    writeFileSync(join(generatedDir, descriptorModuleName), descriptorModule);
  }
} finally {
  rmSync(temporaryRoot, { recursive: true, force: true });
}
